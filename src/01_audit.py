_lines = []


def log(msg=""):
    print(msg)
    _lines.append(str(msg))


def section(title):
    log()
    log("=" * 74)
    log(title)
    log("=" * 74)


def check(name, passed, detail):
    """One rule -> one verdict line.

    Coerce the flag with bool(): pandas returns numpy.bool_, and
    `numpy.True_ is True` is False, so identity comparison turns passes
    into fails. This bug ships to production constantly.
    """
    if isinstance(passed, str):
        verdict = "WARN"
    else:
        verdict = "PASS" if bool(passed) else "FAIL"
    log(f"[{verdict}] {name}")
    log(f"        {detail}")
    return verdict


results = []


def load(key, **kw):
    df = pd.read_csv(RAW[key], **kw)
    log(f"{key:15s}: {df.shape[0]:>7,} rows x {df.shape[1]:>2} cols")
    return df


