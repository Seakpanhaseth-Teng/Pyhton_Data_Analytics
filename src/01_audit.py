"""
TICKET T01 — Data Audit (v2 dataset)
====================================
Pairs with: tickets/T01-data-audit.md
Owner: me (demo section). You rebuild T02 the same way.

WHY THIS FILE EXISTS
--------------------
Every real engagement starts with an audit, not a chart. If you build a
dashboard on top of dirty data, you have automated a lie. The audit has one
job: decide, rule by rule, whether this dataset is fit to report on.

Each check produces PASS / WARN / FAIL plus the number that justifies it.
The output goes to output/audit_report.txt so it can be attached to the
ticket as evidence.

v2 covers the nine-table extract generated by tools/make_dataset.py, not the
old two-sheet practice workbook.

Run:  python src/01_audit.py
"""

