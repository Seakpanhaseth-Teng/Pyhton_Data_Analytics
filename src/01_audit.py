section("1. COMPLETENESS")
ALLOWED_NULLS = {
    "churn_date",              # null iff active
    "payment_method",          # planted nulls - must be counted, not dropped
    "price_effective_from",    # never-revised products only
    "holiday_name",            # only populated on holidays
}
for name, df in (("fact_sales", sales), ("fact_customer_month", cm),
                 ("dim_customer", cust), ("dim_rep", reps)):
    nulls = df.isna().sum()
    offenders = nulls[(nulls > 0) & (~nulls.index.isin(ALLOWED_NULLS))]
    results.append(check(
        f"No unexpected nulls in {name}",
        offenders.empty,
        "none" if offenders.empty else f"unexpected: {offenders.to_dict()}",
    ))

expected_days = pd.date_range(DATA_START, DATA_END).size
present_days = cal["date"].nunique()
results.append(check(
    "Calendar covers every day in the period",
    present_days == expected_days,
    f"{present_days}/{expected_days} days ({DATA_START} to {DATA_END})",
))

covered = sales["txn_date"].dt.normalize().nunique()
results.append(check(
    "Sales activity on every calendar day",
    covered == expected_days,
    f"{covered}/{expected_days} days have at least one transaction",
))

gaps = 0
for _, g in cm.groupby("customer_id"):
    months = sorted(g["month"])
    idx = [int(m[:4]) * 12 + int(m[5:7]) for m in months]
    if any(b - a != 1 for a, b in zip(idx, idx[1:])):
        gaps += 1
results.append(check(
    "Customer-month snapshots are contiguous",
    gaps == 0,
    f"{gaps} customers have a missing month between signup and churn",
))

