section("7. OUTLIERS (IQR rule, 1.5 x IQR)")


def iqr_outlier_pct(series):
    q1, q3 = series.quantile([0.25, 0.75])
    iqr = q3 - q1
    if iqr == 0:
        return 0.0, 0
    mask = (series < q1 - 1.5 * iqr) | (series > q3 + 1.5 * iqr)
    return float(mask.mean()), int(mask.sum())


for label, series in (
    ("fact_sales.net_revenue_usd", clean["net_revenue_usd"]),
    ("fact_sales.units", clean["units"]),
    ("fact_customer_month.mrr_usd", cm["mrr_usd"]),
):
    pct, n = iqr_outlier_pct(series)
    results.append(check(
        f"Outlier share: {label}",
        pct <= MAX_OUTLIER_PCT,
        f"{n:,} rows = {pct:.1%} outside 1.5xIQR (tolerance {MAX_OUTLIER_PCT:.0%})",
    ))

# data_usage_gb is bimodal by plan: a prepaid SIM draws a few GB while a
# leased line draws hundreds. Pooling the plans makes every broadband
# customer look like an outlier, so judge each plan against its own IQR.
# plan_type lives on dim_customer, not on the monthly fact.
usage = cm[["customer_id", "data_usage_gb"]].merge(
    cust[["customer_id", "plan_type"]], on="customer_id", how="left")
usage["plan"] = usage["plan_type"].str.strip().str.lower()
worst_pct, worst_n, worst_plan = 0.0, 0, "-"
for plan, g in usage.groupby("plan"):
    pct, n = iqr_outlier_pct(g["data_usage_gb"])
    if pct > worst_pct:
        worst_pct, worst_n, worst_plan = pct, n, plan
results.append(check(
    "Outlier share: fact_customer_month.data_usage_gb (within plan)",
    worst_pct <= MAX_OUTLIER_PCT,
    f"worst plan {worst_plan}: {worst_n:,} rows = {worst_pct:.1%} "
    f"outside 1.5xIQR (tolerance {MAX_OUTLIER_PCT:.0%})",
))

